#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md from `cargo metadata` and the desktop
app's production npm dependencies. Run from the repository root."""
import json, subprocess, os

HEADER = """# Third-party notices

ClipFX Enhance is MIT licensed. It is built on the open-source components below.
This file is generated by `tools/gen_notices.py`; the license texts are in each
component's source distribution (crates.io / npmjs.com), linked by name.

## Main components

| Component | Use | License |
|---|---|---|
| FFmpeg / FFprobe | decoding, filtering, encoding, muxing (separate executables, called by path) | LGPL-2.1+ or GPL-2.0+ depending on the build. Linux and macOS packages use the system FFmpeg. The Windows installer ships a GPL build from BtbN/FFmpeg-Builds (includes vid.stab, GPL, and zimg, WTFPL); its license and source location are in `ffmpeg/FFMPEG_LICENSE.txt` and `ffmpeg/FFMPEG_SOURCE.txt` next to the program. |
| candle | neural-network inference in Rust | MIT OR Apache-2.0 |
| Tauri | desktop shell | MIT OR Apache-2.0 |
| System web view (WebView2 / WebKit / WKWebView) | user interface rendering | provided by the operating system |
| SQLite (via rusqlite, bundled) | local database | Public domain |
| React, React DOM | user interface | MIT |
| Lucide icons | icons | ISC |
| zustand | UI state | MIT |

AI model weights are not part of ClipFX Enhance. See [MODEL_LICENSES.md](MODEL_LICENSES.md).
"""

def rust():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], text=True))
    rows = sorted({(p["name"], p["version"], p.get("license") or "see crate", p.get("repository") or "") for p in meta["packages"] if p.get("source")})
    return rows

def npm():
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"], cwd="apps/desktop", capture_output=True, text=True).stdout
    tree = json.loads(out or "{}")
    seen = {}
    def walk(deps):
        for name, d in (deps or {}).items():
            v = d.get("version")
            if not v or (name, v) in seen:
                continue
            pj = os.path.join("apps/desktop/node_modules", name, "package.json")
            lic = "see package"
            if os.path.exists(pj):
                lic = json.load(open(pj)).get("license") or lic
            seen[(name, v)] = lic
            walk(d.get("dependencies"))
    walk(tree.get("dependencies"))
    return sorted((n, v, l) for (n, v), l in seen.items())

lines = [HEADER, "## Rust crates (all platforms)", "", "| Crate | Version | License |", "|---|---|---|"]
lines += [f"| {n} | {v} | {l} |" for n, v, l, _ in rust()]
lines += ["", "## JavaScript packages (shipped in the user interface)", "", "| Package | Version | License |", "|---|---|---|"]
lines += [f"| {n} | {v} | {l} |" for n, v, l in npm()]
open("THIRD_PARTY_NOTICES.md", "w").write("\n".join(lines) + "\n")
